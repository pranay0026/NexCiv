                "class CivicVisionFeatureExtractor:\n",
                "    \"\"\"\n",
                "    Extracts visual features from civic complaint images using pre-trained convolutional backbones.\n",
                "    Computes visual defect vectors and heuristic damage descriptors (contrast, gradient, luminance).\n",
                "    \"\"\"\n",
                "    def __init__(self):\n",
                "        if HAS_TORCH:\n",
                "            self.model = models.mobilenet_v3_small(weights=models.MobileNet_V3_Small_Weights.DEFAULT)\n",
                "            self.model.classifier = nn.Identity()  # Extract raw 576-dim embedding\n",
                "            self.model.eval()\n",
                "            self.model.to(device)\n",
                "            self.transform = transforms.Compose([\n",
                "                transforms.Resize((224, 224)),\n",
                "                transforms.ToTensor(),\n",
                "                transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])\n",
                "            ])\n",
                "        else:\n",
                "            self.model = None\n",
                "\n",
                "    def extract_features(self, img_pil):\n",
                "        \"\"\"Extract feature embedding from a PIL Image.\"\"\"\n",
                "        if HAS_TORCH and self.model is not None:\n",
                "            try:\n",
                "                tensor = self.transform(img_pil.convert('RGB')).unsqueeze(0).to(device)\n",
                "                with torch.no_grad():\n",
                "                    return self.model(tensor).cpu().numpy().flatten()\n",
                "            except Exception:\n",
                "                return np.zeros(576, dtype=np.float32)\n",
                "        else:\n",
                "            # Fast NumPy spatial descriptor (Color moments + gradient)\n",
                "            rgb = img_pil.convert('RGB').resize((64, 64))\n",
                "            arr = np.array(rgb, dtype=np.float32) / 255.0\n",
                "            r_hist, _ = np.histogram(arr[:, :, 0], bins=16, range=(0, 1))\n",
                "            g_hist, _ = np.histogram(arr[:, :, 1], bins=16, range=(0, 1))\n",
                "            b_hist, _ = np.histogram(arr[:, :, 2], bins=16, range=(0, 1))\n",
                "            gray = np.array(img_pil.convert('L').resize((64, 64)), dtype=np.float32)\n",
                "            gy, gx = np.gradient(gray)\n",
                "            grad_hist, _ = np.histogram(np.sqrt(gx**2 + gy**2), bins=16, range=(0, 100))\n",
                "            features = np.concatenate([r_hist, g_hist, b_hist, grad_hist]).astype(np.float32)\n",
                "            return features / (np.linalg.norm(features) + 1e-6)\n",
                "\n",
                "    def compute_visual_damage_metrics(self, img_pil):\n",
                "        \"\"\"Computes contrast, luminance, edge roughness, and simulated visual defect score.\"\"\"\n",
                "        gray = np.array(img_pil.convert('L'))\n",
                "        contrast = float(np.std(gray))\n",
                "        brightness = float(np.mean(gray))\n",
                "        edges = img_pil.filter(ImageFilter.FIND_EDGES)\n",
                "        edge_density = float(np.mean(np.array(edges.convert('L'))))\n",
                "\n",
                "        severity_score = min(100.0, contrast * 1.2 + edge_density * 0.8)\n",
                "        return {\n",
                "            'contrast': round(contrast, 2),\n",
                "            'brightness': round(brightness, 2),\n",
                "            'edge_density': round(edge_density, 2),\n",
                "            'visual_severity_score': round(severity_score, 1)\n",
                "        }\n",
                "\n",
                "vision_extractor = CivicVisionFeatureExtractor()\n",
