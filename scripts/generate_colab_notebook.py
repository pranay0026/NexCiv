    "# Image transforms for civic complaints\n",
    "image_transform = transforms.Compose([\n",
    "    transforms.Resize((224, 224)),\n",
    "    transforms.ToTensor(),\n",
    "    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])\n",
    "])\n",
    "\n",
    "def classify_civic_image(img_input):\n",
    "    \"\"\"\n",
    "    Accepts PIL Image, file path, or image bytes and predicts civic wing and visual urgency.\n",
    "    \"\"\"\n",
    "    if isinstance(img_input, str):\n",
    "        img = Image.open(img_input).convert('RGB')\n",
    "    elif isinstance(img_input, bytes):\n",
    "        img = Image.open(io.BytesIO(img_input)).convert('RGB')\n",
    "    else:\n",
    "        img = img_input.convert('RGB')\n",
    "        \n",
    "    tensor = image_transform(img).unsqueeze(0)\n",
    "    with torch.no_grad():\n",
    "        logits = vision_model(tensor)\n",
    "        probs = torch.softmax(logits, dim=1).numpy()[0]\n",
    "        \n",
    "    pred_idx = np.argmax(probs)\n",
    "    predicted_wing = WINGS[pred_idx]\n",
    "    confidence = float(probs[pred_idx])\n",
    "    \n",
    "    # Visual severity estimation based on image contrast & depth\n",
    "    gray = np.array(img.convert('L'))\n",
    "    std_contrast = np.std(gray)\n",
    "    if std_contrast > 65:\n",
    "        visual_priority = 'Critical'\n",
    "    elif std_contrast > 45:\n",
    "        visual_priority = 'High'\n",
    "    else:\n",
    "        visual_priority = 'Medium'\n",
    "        \n",
    "    return {\n",
    "        'wing': predicted_wing,\n",
    "        'confidence': confidence,\n",
    "        'visual_priority': visual_priority\n",
    "    }"
