    "# Define PyTorch Image Classifier for Civic Wings\n",
    "class CivicVisionClassifier(nn.Module):\n",
    "    def __init__(self, num_classes=5):\n",
    "        super(CivicVisionClassifier, self).__init__()\n",
    "        # Use MobileNetV2 pretrained on ImageNet\n",
    "        self.backbone = models.mobilenet_v2(weights=models.MobileNet_V2_Weights.DEFAULT)\n",
    "        # Freeze base features for rapid transfer learning\n",
    "        for param in self.backbone.features.parameters():\n",
    "            param.requires_grad = False\n",
    "        # Replace classification head with Civic Wings classifier\n",
    "        in_features = self.backbone.classifier[1].in_features\n",
    "        self.backbone.classifier = nn.Sequential(\n",
    "            nn.Dropout(p=0.2),\n",
    "            nn.Linear(in_features, 128),\n",
    "            nn.ReLU(),\n",
    "            nn.Linear(128, num_classes)\n",
    "        )\n",
    "        \n",
    "    def forward(self, x):\n",
    "        return self.backbone(x)\n",
    "\n",
    "vision_model = CivicVisionClassifier(num_classes=len(WINGS))\n",
    "vision_model.eval()\n",
