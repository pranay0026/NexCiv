    "PRIORITY_LEVELS = {'Critical': 4, 'High': 3, 'Medium': 2, 'Low': 1}\n",
    "LEVEL_TO_PRIORITY = {4: 'Critical', 3: 'High', 2: 'Medium', 1: 'Low'}\n",
    "\n",
    "def multimodal_classify(text: str, image=None):\n",
    "    result = {}\n",
    "    \n",
    "    # 1. Text inference\n",
    "    text_wing = wing_pipeline.predict([text])[0]\n",
    "    text_wing_conf = float(np.max(wing_pipeline.predict_proba([text])[0]))\n",
    "    \n",
    "    text_prio = prio_pipeline.predict([text])[0]\n",
    "    text_prio_conf = float(np.max(prio_pipeline.predict_proba([text])[0]))\n",
    "    \n",
    "    result['wing'] = text_wing\n",
    "    result['wing_confidence'] = text_wing_conf\n",
    "    result['priority'] = text_prio\n",
    "    result['priority_confidence'] = text_prio_conf\n",
    "    \n",
    "    # 2. Image inference (if provided)\n",
    "    if image is not None:\n",
    "        img_res = classify_civic_image(image)\n",
    "        result['image_wing'] = img_res['wing']\n",
    "        result['image_priority'] = img_res['visual_priority']\n",
    "        \n",
    "        # Safety-first fusion for priority (whichever is more urgent takes precedence)\n",
    "        max_prio_level = max(\n",
    "            PRIORITY_LEVELS.get(text_prio, 2),\n",
    "            PRIORITY_LEVELS.get(img_res['visual_priority'], 2)\n",
    "        )\n",
    "        result['priority'] = LEVEL_TO_PRIORITY[max_prio_level]\n",
    "        \n",
    "    return result\n",
    "\n",
