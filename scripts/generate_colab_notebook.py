    "\n",
    "If the citizen provides both a text description AND an uploaded photo:\n",
    "- The text classifier determines the civic keywords.\n",
    "- The vision model confirms the visual domain.\n",
    "- The priority engine assigns the most urgent level (safety-first heuristic: if either text or image indicates Critical/High, the complaint is prioritized)."
