CORPORATION_DICT = {c["code"]: c for c in AP_MUNICIPAL_CORPORATIONS}

def get_corporation(code_or_name: str):
    if not code_or_name:
        return AP_MUNICIPAL_CORPORATIONS[0]
    cleaned = code_or_name.strip().upper()
    if cleaned in CORPORATION_DICT:
        return CORPORATION_DICT[cleaned]
    for c in AP_MUNICIPAL_CORPORATIONS:
        if cleaned in c["name"].upper() or cleaned in c["short_name"].upper():
            return c
    return AP_MUNICIPAL_CORPORATIONS[0]
